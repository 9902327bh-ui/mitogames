function buildControlStepData(light: number, co2: number, temp: number, labelOverride?: string) {
  const res = computePhotosynthesisRate(light, co2, temp);
  const limiting = labelOverride ?? res.limitingFactor;
  return {
    rate: res.rate,
    readouts: [
      { label: 'RATE', value: `${res.rate} bubbles/min` },
      { label: 'LIMITING FACTOR', value: limiting },
      { label: 'TEMP °C', value: `${temp} °C` },
    ],
    controlValues: { light, co2, temp, label: limiting },
  };
}

